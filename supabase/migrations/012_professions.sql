-- =====================================================
-- 5. Internal ANN helpers — NOT granted to anon.
--
-- pgvector ordering (`ORDER BY embedding <=> query_embedding`) isn't
-- expressible via PostgREST filters, so build-profession-index (which
-- runs under the service role, but still talks to Postgres only via
-- PostgREST/RPC through supabase-js) needs these as SECURITY DEFINER
-- RPCs. They are intentionally not part of the public contract: no
-- GRANT to anon/authenticated, only to service_role (implicit — RLS
-- and grants don't apply to the role used by the service key, but we
-- REVOKE FROM PUBLIC defensively and never GRANT to anon/authenticated
-- so a leaked anon key can't call them to enumerate arbitrary
-- job/news rows by an attacker-supplied embedding).
-- =====================================================

CREATE OR REPLACE FUNCTION _match_jobs_for_embedding(
  query_embedding vector(1536),
  match_count int DEFAULT 15
)
RETURNS TABLE (job_id text)
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT v.job_id
  FROM vagas_ia v
  WHERE v.status = 'active'
    AND v.embedding IS NOT NULL
  ORDER BY v.embedding <=> query_embedding
  LIMIT LEAST(GREATEST(COALESCE(match_count, 15), 1), 50);
$$;

REVOKE ALL ON FUNCTION _match_jobs_for_embedding(vector, int) FROM PUBLIC;

CREATE OR REPLACE FUNCTION _match_news_for_embedding(
  query_embedding vector(1536),
  match_count int DEFAULT 8
)
RETURNS TABLE (news_id uuid)
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT n.id
  FROM news n
  WHERE (n.status = 'published' OR n.status IS NULL)
    AND n.embedding IS NOT NULL
  ORDER BY n.embedding <=> query_embedding
  LIMIT LEAST(GREATEST(COALESCE(match_count, 8), 1), 50);
$$;

REVOKE ALL ON FUNCTION _match_news_for_embedding(vector, int) FROM PUBLIC;

-- =====================================================
-- 6. RPC profession_jobs — active jobs by cosine to profession
-- embedding, published professions only.
-- =====================================================

CREATE OR REPLACE FUNCTION profession_jobs(
  profession_slug text,
  match_count int DEFAULT 12
)
RETURNS TABLE (
  id uuid,
  job_id text,
  job_title text,
  company_name text,
  job_url text,
  logo_url text,
  location text,
  is_remote boolean,
  seniority_level text,
  posted_at timestamptz
)
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT v.id, v.job_id, v.job_title, v.company_name, v.job_url, v.logo_url, v.location, v.is_remote, v.seniority_level, v.posted_at
  FROM vagas_ia v
  JOIN professions p ON p.slug = profession_slug
  WHERE p.status = 'published'
    AND p.embedding IS NOT NULL
    AND v.embedding IS NOT NULL
    AND v.status = 'active'
  ORDER BY v.embedding <=> p.embedding
  -- Clamp: anon can call this RPC directly via PostgREST; never allow a bulk dump
  LIMIT LEAST(GREATEST(COALESCE(match_count, 12), 1), 24);
$$;

REVOKE ALL ON FUNCTION profession_jobs(text, int) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION profession_jobs(text, int) TO anon, authenticated;

-- =====================================================
-- 7. RPC profession_news — published news by cosine to profession
-- embedding, published professions only. Mirrors niche_news column
-- types exactly.
-- =====================================================

CREATE OR REPLACE FUNCTION profession_news(
  profession_slug text,
  match_count int DEFAULT 6
)
RETURNS TABLE (
  id uuid,
  slug text,
  title text,
  subtitle text,
  cover_image text,
  category text,
  published_at timestamptz,
  author text,
  read_time text
)
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT n.id, n.slug, n.title, n.subtitle, n.cover_image, n.category, n.published_at, n.author, n.read_time
  FROM news n
  JOIN professions p ON p.slug = profession_slug
  WHERE p.status = 'published'
    AND p.embedding IS NOT NULL
    AND n.embedding IS NOT NULL
    AND (n.status = 'published' OR n.status IS NULL)
    AND n.published_at >= now() - interval '90 days'
  ORDER BY n.embedding <=> p.embedding
  LIMIT LEAST(GREATEST(COALESCE(match_count, 6), 1), 24);
$$;

REVOKE ALL ON FUNCTION profession_news(text, int) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION profession_news(text, int) TO anon, authenticated;

-- =====================================================
-- 8. RPC quiz_professions — published professions for the quiz flow,
-- ordered by cluster then name (frontend lists clusters, then the
-- professions within each).
-- =====================================================

CREATE OR REPLACE FUNCTION quiz_professions()
RETURNS TABLE (
  slug text,
  name text,
  cluster text
)
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT p.slug, p.name, p.cluster
  FROM professions p
  WHERE p.status = 'published'
  ORDER BY p.cluster, p.name;
$$;

REVOKE ALL ON FUNCTION quiz_professions() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION quiz_professions() TO anon, authenticated;

