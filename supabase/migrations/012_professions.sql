-- =====================================================
-- PROFESSIONS — "Sua profissão está em risco?" hub + quiz
--
-- Product goal: a non-tech visitor picks their profession (or answers
-- the quiz) and sees an AI-exposure verdict for it — how much of the
-- day-to-day is likely to be augmented vs. automated by generative AI
-- in Brazil over the next 3-5 years — backed by real job postings and
-- news, not a generic take.
--
-- Architecture mirrors 010_niches.sql: one embedding per profession
-- (computed once from name+descriptor), ANN search against the
-- existing news.embedding / vagas_ia.embedding columns via <=>
-- (cosine distance). The exposure verdict itself (exposure_score,
-- summary, tasks_augmented/at_risk, bridge_skills) is generated by the
-- build-profession-index edge function (gpt-4o-mini, JSON mode) from
-- that evidence, and always lands in status='review' — a human must
-- flip it to 'published' in Studio. This migration only creates the
-- schema and seeds the descriptive columns (name/cluster/descriptor),
-- never the generated fields.
-- =====================================================

CREATE EXTENSION IF NOT EXISTS vector;

-- =====================================================
-- 1. professions — table
-- =====================================================

CREATE TABLE IF NOT EXISTS professions (
  slug text PRIMARY KEY,
  name text NOT NULL,
  cluster text NOT NULL,
  descriptor text NOT NULL,
  exposure_score int,
  exposure_band text,
  summary text,
  tasks_augmented jsonb,
  tasks_at_risk jsonb,
  bridge_skills jsonb,
  evidence_job_ids text[],
  evidence_news_ids uuid[],
  embedding vector(1536),
  status text NOT NULL DEFAULT 'draft',
  generated_at timestamptz,
  model text,
  reviewed_at timestamptz,
  sort_order int NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Constraints added separately (can't IF NOT EXISTS a CHECK constraint directly)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'professions_cluster_check'
  ) THEN
    ALTER TABLE professions
      ADD CONSTRAINT professions_cluster_check
      CHECK (cluster IN ('negocios','saude','educacao','juridico','financas','marketing','tecnologia','criativo','operacoes','servicos'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'professions_exposure_score_check'
  ) THEN
    ALTER TABLE professions
      ADD CONSTRAINT professions_exposure_score_check
      CHECK (exposure_score IS NULL OR (exposure_score >= 0 AND exposure_score <= 100));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'professions_exposure_band_check'
  ) THEN
    ALTER TABLE professions
      ADD CONSTRAINT professions_exposure_band_check
      CHECK (exposure_band IS NULL OR exposure_band IN ('baixa','media','alta'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'professions_status_check'
  ) THEN
    ALTER TABLE professions
      ADD CONSTRAINT professions_status_check
      CHECK (status IN ('draft','review','published','rejected'));
  END IF;
END $$;

COMMENT ON COLUMN professions.descriptor IS
  '2-3 factual sentences (PT-BR) describing what the profession does day to day. Seed input for the embedding ("{name}. {descriptor}") and for the LLM exposure evaluation — never shown verbatim to end users (excluded from professions_public).';
COMMENT ON COLUMN professions.summary IS
  '3-5 sentence PT-BR verdict written by build-profession-index using non-deterministic language ("tende a", "parte das tarefas") — never a flat percentage claim.';
COMMENT ON COLUMN professions.evidence_job_ids IS
  'vagas_ia.job_id values used as evidence for the exposure verdict (up to 15). Required non-empty before build-profession-index will persist a verdict — see docs/PROFESSIONS.md governance rules.';
COMMENT ON COLUMN professions.embedding IS
  'text-embedding-3-small (1536d) over "{name}. {descriptor}". Populated by build-profession-index (service-role client) — never computed client-side. NULL until first generated; profession_jobs/profession_news return an empty set for a profession whose embedding is still NULL.';
COMMENT ON COLUMN professions.status IS
  'draft: seeded, not yet evaluated. review: LLM verdict generated, awaiting human review. published: live on the public site. rejected: reviewed and discarded (bad evidence/verdict) — kept for audit, never published.';

CREATE INDEX IF NOT EXISTS idx_professions_embedding_hnsw
  ON professions USING hnsw (embedding vector_cosine_ops);

CREATE INDEX IF NOT EXISTS idx_professions_status ON professions (status);

-- =====================================================
-- 2. RLS — table locked down entirely for public roles, same rationale
-- as niches: exposes embedding/descriptor otherwise (RLS is row-level,
-- not column-level). professions_public is the only public surface.
-- =====================================================

ALTER TABLE professions ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON professions FROM anon, authenticated;

DROP POLICY IF EXISTS "Block direct select on professions" ON professions;
CREATE POLICY "Block direct select on professions"
ON professions FOR SELECT
TO anon, authenticated
USING (false);

DROP POLICY IF EXISTS "Block direct writes on professions" ON professions;
CREATE POLICY "Block direct writes on professions"
ON professions FOR ALL
TO anon, authenticated
USING (false)
WITH CHECK (false);

-- =====================================================
-- 3. professions_public — view without embedding/descriptor,
-- published only. sort_order first, then name, mirrors niches_public
-- ordering conventions used by the frontend hub index.
-- =====================================================

CREATE OR REPLACE VIEW professions_public AS
SELECT
  slug, name, cluster,
  exposure_score, exposure_band, summary,
  tasks_augmented, tasks_at_risk, bridge_skills,
  status, reviewed_at, sort_order, updated_at
FROM professions
WHERE status = 'published';

GRANT SELECT ON professions_public TO anon, authenticated;

